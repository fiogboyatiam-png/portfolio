const projectModal =
    document.getElementById("projectModal");

const projectModalTag =
    document.getElementById("projectModalTag");

const projectModalTitle =
    document.getElementById("projectModalTitle");

const projectModalDescription =
    document.getElementById("projectModalDescription");

const projectGallery =
    document.getElementById("projectGallery");

const projectModalLink =
    document.getElementById("projectModalLink");


function openProjectModal(projectId) {

    const project =
        projectData[projectId];


    if (!project) {
        return;
    }


    const isFrench =
        currentLanguage === "fr";


    projectModalTag.textContent =
        isFrench
            ? project.tagFr
            : project.tagEn;


    projectModalTitle.textContent =
        isFrench
            ? project.titleFr
            : project.titleEn;


    projectModalDescription.textContent =
        isFrench
            ? project.descriptionFr
            : project.descriptionEn;


    projectGallery.innerHTML = "";


    if (
        !project.images ||
        project.images.length === 0
    ) {

        const empty =
            document.createElement("div");

        empty.className =
            "gallery-empty";

        empty.textContent =
            isFrench
                ? "Les captures seront ajoutées prochainement."
                : "Screenshots will be added soon.";

        projectGallery.appendChild(empty);

    } else {

        project.images.forEach(
            (image, index) => {

                const item =
                    document.createElement("button");

                item.type = "button";

                item.className =
                    "gallery-item touch-effect";


                const imageElement =
                    document.createElement("img");

                imageElement.src =
                    image.src;

                imageElement.loading =
                    "lazy";

                imageElement.alt =
                    isFrench
                        ? image.titleFr
                        : image.titleEn;


                const label =
                    document.createElement("span");

                label.textContent =
                    isFrench
                        ? image.titleFr
                        : image.titleEn;


                item.appendChild(imageElement);

                item.appendChild(label);


                item.addEventListener(
                    "click",
                    () => {

                        openImageModal(
                            image.src,

                            isFrench
                                ? image.titleFr
                                : image.titleEn,

                            isFrench
                                ? `Capture ${index + 1} du projet.`
                                : `Screenshot ${index + 1} of the project.`
                        );

                    }
                );


                projectGallery.appendChild(item);

            }
        );

    }


    if (project.link) {

        projectModalLink.href =
            project.link;

        projectModalLink.style.display =
            "inline-flex";

        projectModalLink.textContent =
            isFrench
                ? "Voir le site →"
                : "Visit website →";

    } else {

        projectModalLink.style.display =
            "none";

    }


    openModal(projectModal);

}


document
    .querySelectorAll("[data-open-project]")
    .forEach((button) => {

        button.addEventListener(
            "click",
            (event) => {

                event.stopPropagation();

                const projectId =
                    button.dataset.openProject;

                openProjectModal(projectId);

            }
        );

    });


