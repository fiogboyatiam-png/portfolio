/* =========================================================
   CV (FR / EN)
   Ajoute assets/CV_Norel_Fiogbo_EN.pdf pour activer le CV anglais.
   Sans ce fichier, le CV français est proposé.
========================================================= */

const CV_FR = "assets/CV_Norel_FR.pdf";
const CV_EN = "assets/CV_Norel_EN.pdf";

function setCvLink(url) {

    if (!cvBtn) {
        return;
    }

    cvBtn.href = url;

    cvBtn.setAttribute(
        "download",
        url.split("/").pop()
    );

}

function updateCvLink(language) {

    setCvLink(CV_FR);

    if (language === "en") {

        fetch(CV_EN, { method: "HEAD" })
            .then((response) => {

                if (response.ok) {
                    setCvLink(CV_EN);
                }

            })
            .catch(() => {});

    }

}


/* =========================================================
   LANGUE
========================================================= */

function applyLanguage(language) {

    currentLanguage = language;

    localStorage.setItem(
        "portfolio-language",
        language
    );

    document.documentElement.lang = language;


    document
        .querySelectorAll("[data-i18n]")
        .forEach((element) => {

            const key =
                element.getAttribute("data-i18n");

            if (
                translations[language] &&
                translations[language][key]
            ) {

                element.textContent =
                    translations[language][key];

            }

        });


    document
        .querySelectorAll(
            "[data-placeholder-fr][data-placeholder-en]"
        )
        .forEach((input) => {

            input.placeholder =
                language === "fr"
                    ? input.dataset.placeholderFr
                    : input.dataset.placeholderEn;

        });


    languageIcon.textContent =
        language === "fr"
            ? "EN"
            : "FR";


    languageBtn.setAttribute(
        "aria-label",
        language === "fr"
            ? "Passer en anglais"
            : "Switch to French"
    );

    updateCvLink(language);

}


