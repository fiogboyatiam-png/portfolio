function applyTheme(theme) {

    currentTheme = theme;

    body.dataset.theme = theme;

    localStorage.setItem(
        "portfolio-theme",
        theme
    );


    themeIcon.textContent =
        theme === "dark"
            ? "☀"
            : "☾";


    themeBtn.setAttribute(
        "aria-label",
        theme === "dark"
            ? "Activer le mode clair"
            : "Activer le mode sombre"
    );

}


themeBtn.addEventListener(
    "click",
    () => {

        const newTheme =
            currentTheme === "dark"
                ? "light"
                : "dark";

        applyTheme(newTheme);

    }
);


