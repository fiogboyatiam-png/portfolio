function renderExperienceMedia() {

    const grid =
        document.getElementById("experienceMediaGrid");


    if (!grid) {
        return;
    }


    grid.innerHTML = "";


    const isFrench =
        currentLanguage === "fr";


    experienceMedia.forEach(
        (media) => {

            const card =
                document.createElement("article");

            card.className =
                "experience-media-card touch-effect";


            if (media.type === "image") {

                const image =
                    document.createElement("img");

                image.className =
                    "experience-media-image";

                image.src =
                    media.file;

                image.alt =
                    isFrench
                        ? media.titleFr
                        : media.titleEn;


                card.appendChild(image);


                card.addEventListener(
                    "click",
                    () => {

                        openImageModal(
                            media.file,

                            isFrench
                                ? media.titleFr
                                : media.titleEn,

                            isFrench
                                ? media.descriptionFr
                                : media.descriptionEn
                        );

                    }
                );

            } else {

                const preview =
                    document.createElement("div");

                preview.className =
                    "document-preview";


                const icon =
                    document.createElement("div");

                icon.className =
                    "document-icon";

                icon.textContent =
                    "PDF";


                const text =
                    document.createElement("strong");

                text.textContent =
                    isFrench
                        ? "Ouvrir le document"
                        : "Open document";


                preview.appendChild(icon);

                preview.appendChild(text);

                card.appendChild(preview);


                card.addEventListener(
                    "click",
                    () => {

                        window.open(
                            media.file,
                            "_blank"
                        );

                    }
                );

            }


            const content =
                document.createElement("div");

            content.className =
                "experience-media-content";


            const title =
                document.createElement("h4");

            title.textContent =
                isFrench
                    ? media.titleFr
                    : media.titleEn;


            const description =
                document.createElement("p");

            description.textContent =
                isFrench
                    ? media.descriptionFr
                    : media.descriptionEn;


            content.appendChild(title);

            content.appendChild(description);

            card.appendChild(content);

            grid.appendChild(card);

        }
    );

}


