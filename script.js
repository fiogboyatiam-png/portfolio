const contactForm =
    document.getElementById("contactForm");

const formMessage =
    document.getElementById("formMessage");


if (contactForm) {

    contactForm.addEventListener(
        "submit",
        async (event) => {

            event.preventDefault();


            const name =
                document
                    .getElementById("name")
                    .value
                    .trim();


            const email =
                document
                    .getElementById("email")
                    .value
                    .trim();


            const subject =
                document
                    .getElementById("subject")
                    .value
                    .trim();


            const message =
                document
                    .getElementById("message")
                    .value
                    .trim();


            const formAction =
                contactForm.getAttribute("action");

            const isConfigured =
                formAction &&
                !formAction.includes("VOTRE_ID_FORMSPREE");


            if (!isConfigured) {

                const emailSubject =
                    encodeURIComponent(subject);

                const emailBody =
                    encodeURIComponent(
                        `Nom : ${name}\nEmail : ${email}\n\n${message}`
                    );

                window.location.href =
                    `mailto:fiogboyatiam@gmail.com?subject=${emailSubject}&body=${emailBody}`;

                formMessage.textContent =
                    currentLanguage === "fr"
                        ? "Votre messagerie va s’ouvrir pour envoyer le message."
                        : "Your email application will open to send the message.";

                return;

            }


            formMessage.textContent =
                currentLanguage === "fr"
                    ? "Envoi en cours..."
                    : "Sending...";


            try {

                const response =
                    await fetch(formAction, {
                        method: "POST",
                        headers: {
                            Accept: "application/json"
                        },
                        body: new FormData(contactForm)
                    });


                if (response.ok) {

                    formMessage.textContent =
                        currentLanguage === "fr"
                            ? "Message envoyé avec succès. Merci !"
                            : "Message sent successfully. Thank you!";

                    contactForm.reset();

                } else {

                    throw new Error("Formspree error");

                }

            } catch (error) {

                formMessage.textContent =
                    currentLanguage === "fr"
                        ? "L’envoi a échoué. Écrivez-moi directement à fiogboyatiam@gmail.com."
                        : "Sending failed. Please email me directly at fiogboyatiam@gmail.com.";

            }

        }
    );

}


